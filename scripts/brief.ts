// The general seat brief: TeamCLI's built-in default, embedded in the package the way the
// registered captures are, because a build ships dist/ only and must never read a documentation
// checkout at runtime. The canonical source lives in this repository at docs/briefs/general.md;
// the build ships the embedded copy and its sha256, and CI compares the two byte for byte.
//
//   bun run brief --write                writes src/launch/general-brief-text.ts from docs/briefs/general.md
//   bun run brief --write <source>       writes it from another copy of the same text
//   bun run brief:check                  checks the pin and compares with docs/briefs/general.md
//   bun run brief:check -- --source <source>
//   TEAM_BRIEF_SOURCE=<source> bun run brief:check
//                                        compares the embedded text with that source instead,
//                                        byte for byte, and names the first line that differs
//
// The source is markdown: an optional frontmatter block, then the brief's own text from its first
// heading to the end of the file. The comparison is exact — no trimming, no rewrapping — so the
// package carries the accepted text and nothing else.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const textFile = join(root, 'src', 'launch', 'general-brief-text.ts');
/** The canonical source this repository keeps; an importing machine may pass another copy. */
const repoSource = join(root, 'docs', 'briefs', 'general.md');

/** The brief's own text: what follows the source's frontmatter, from its first heading. */
export function briefOf(source: string): string {
  const lines = source.split('\n');
  let start = 0;
  if (lines[0]?.trim() === '---') {
    const end = lines.findIndex((line, index) => index > 0 && line.trim() === '---');
    if (end === -1) throw new Error('the source opens a frontmatter block and never closes it');
    start = end + 1;
  }
  while (start < lines.length && lines[start]?.trim() === '') start++;
  let text = lines.slice(start).join('\n');
  if (!text.endsWith('\n')) text += '\n';
  if (!text.startsWith('# ')) throw new Error('the source holds no brief: no line starts with "# "');
  return text;
}

/** The text as it sits inside the generated module's template literal. */
function literalOf(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

/** The module the package carries: the text and its sha256, generated, never hand-edited. */
export function textModuleOf(text: string): string {
  const hash = createHash('sha256').update(text).digest('hex');
  return [
    '// Generated by scripts/brief.ts --write from the accepted copy of the general seat brief;',
    '// do not edit. Run `bun run brief --write <source>` after the accepted text changes.',
    `export const GENERAL_BRIEF_SHA256 = ${JSON.stringify(hash)};`,
    'export const GENERAL_BRIEF = `' + literalOf(text) + '`;',
    '',
  ].join('\n');
}

/** Where the source is: `--source <path>`, `TEAM_BRIEF_SOURCE`, or the repository's own
 *  `docs/briefs/general.md`. An option with no path is the invocation's error, exit 2. */
function sourceOf(args: string[]): string | undefined {
  const at = args.indexOf('--source');
  let source: string | undefined;
  if (at !== -1) {
    source = args[at + 1];
    if (source === undefined || source.startsWith('-')) {
      console.error('brief:check: --source needs a path');
      process.exitCode = 2;
      return undefined;
    }
  }
  return source ?? (process.env.TEAM_BRIEF_SOURCE || repoSource);
}

if (import.meta.main) {
  const [mode, value] = process.argv.slice(2);
  if (mode === '--write') {
    if (value !== undefined && value.startsWith('-')) {
      console.error('Usage: bun scripts/brief.ts --write [<source>]');
      process.exitCode = 2;
    } else {
      const source = value ?? repoSource;
      const text = briefOf(readFileSync(source, 'utf8'));
      writeFileSync(textFile, textModuleOf(text));
      const hash = createHash('sha256').update(text).digest('hex');
      console.log(`wrote src/launch/general-brief-text.ts from the source (sha256 ${hash})`);
    }
  } else if (mode === '--check') {
    const source = sourceOf(process.argv.slice(3));
    if (process.exitCode === undefined) {
      const { GENERAL_BRIEF, GENERAL_BRIEF_SHA256 } = await import('../src/launch/general-brief-text.ts');
      const hash = createHash('sha256').update(GENERAL_BRIEF).digest('hex');
      let failed = false;
      if (hash !== GENERAL_BRIEF_SHA256) {
        console.error(
          `src/launch/general-brief-text.ts: the embedded text hashes to ${hash}, and its pinned value is ${GENERAL_BRIEF_SHA256}; run \`bun run brief --write <source>\``,
        );
        failed = true;
      }
      if (source !== undefined) {
        const wanted = briefOf(readFileSync(source, 'utf8'));
        if (wanted !== GENERAL_BRIEF) {
          const lines = GENERAL_BRIEF.split('\n');
          const wantedLines = wanted.split('\n');
          let at = 0;
          while (at < Math.max(lines.length, wantedLines.length) && lines[at] === wantedLines[at]) at++;
          console.error(
            `src/launch/general-brief-text.ts is not the source's text: line ${at + 1} has ${JSON.stringify(lines[at] ?? '<end of file>')}, and the source has ${JSON.stringify(wantedLines[at] ?? '<end of file>')}; run \`bun run brief --write ${source}\``,
          );
          failed = true;
        }
      }
      if (failed) process.exitCode = 1;
      else
        console.log(
          source === undefined
            ? 'src/launch/general-brief-text.ts hashes to its pinned value'
            : 'src/launch/general-brief-text.ts matches the source, byte for byte',
        );
    }
  } else {
    console.error('Usage: bun scripts/brief.ts --write [<source>]\n       bun scripts/brief.ts --check [--source <source>]');
    process.exitCode = 2;
  }
}
